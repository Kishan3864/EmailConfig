// Renders assets/logo.svg to a PNG and writes it into src/lib/logo.ts (base64), so the mail code needs no file access.
//   node scripts/make-logo.cjs
// Email clients do not render SVG, so the signature uses a PNG. It is rendered at 2x for sharp screens,
// on a white background so it stays readable in dark-mode mail clients.
const fs = require("fs");
const path = require("path");
const sharp = require("sharp");

const W = 167, H = 46, PAD = 6, SCALE = 2;
const svg = fs.readFileSync(path.join(__dirname, "../assets/logo.svg"));

(async () => {
  const logo = await sharp(svg, { density: 72 * SCALE * 2 }).resize(W * SCALE, H * SCALE).png().toBuffer();
  const png = await sharp({ create: { width: (W + PAD * 2) * SCALE, height: (H + PAD * 2) * SCALE, channels: 4, background: "#ffffff" } })
    .composite([{ input: logo, left: PAD * SCALE, top: PAD * SCALE }])
    .png({ compressionLevel: 9, palette: true })
    .toBuffer();
  fs.writeFileSync(path.join(__dirname, "../assets/logo.png"), png);
  const out = [
    "// GENERATED by scripts/make-logo.cjs from assets/logo.svg. Do not edit by hand.",
    `export const LOGO_WIDTH = ${W + PAD * 2};`,
    `export const LOGO_HEIGHT = ${H + PAD * 2};`,
    `export const LOGO_PNG_BASE64 =\n  "${png.toString("base64")}";`,
    "",
  ].join("\n");
  fs.writeFileSync(path.join(__dirname, "../src/lib/logo.ts"), out);
  console.log(`logo.png ${png.length} bytes, ${(W + PAD * 2) * SCALE}x${(H + PAD * 2) * SCALE}px`);
})();
